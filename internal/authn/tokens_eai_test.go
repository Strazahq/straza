// buildSessionTokenExample signs one example with the example session key
// and returns its file bytes.
func buildSessionTokenExample(t *testing.T, c sessionTokenExampleCase) []byte {
	t.Helper()
	priv, err := importPrivate(exampleKeyRecord(exampleStrazaSeed))
	if err != nil {
		t.Fatal(err)
	}
	b := jwt.NewBuilder().Issuer(exampleGrantIssuer).Subject(c.sub).JwtID("0199f3a2-5b7c-7d10-8e2f-3a4b5c6d7e51").
		IssuedAt(exampleSessionIat).Expiration(exampleSessionIat.Add(DefaultTokenTTL))
	for name, value := range c.claims {
		b = b.Claim(name, value)
	}
	tok, err := b.Build()
	if err != nil {
		t.Fatal(err)
	}
	signed, err := jwt.Sign(tok, jwt.WithKey(jwa.EdDSA(), priv))
	if err != nil {
		t.Fatal(err)
	}
	pub, err := importPublic(exampleKeyRecord(exampleStrazaSeed))
	if err != nil {
		t.Fatal(err)
	}
	ex := sessionTokenExample{Provenance: exampleSessionProvenance, Description: c.description,
		At: exampleSessionIat.Add(30 * time.Second).Format(time.RFC3339), Key: jsonMap(t, pub), SessionToken: string(signed),
		Header: headerOf(t, string(signed)), Claims: payloadOf(t, string(signed)), Reason: c.reason}
	ex.Verifier.Issuer = exampleGrantIssuer
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(ex); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

// TestSessionTokenExamples regenerates every
// spec/session-token/examples/session-token file and compares bytes, then
// replays each file through Verify at the example's time against the key
// the file publishes. A valid-* example must verify with the eai it shows,
// and an invalid-* one must be refused for eai. Run it with
// STRAZA_UPDATE_SPEC_EXAMPLES=1 to write the files after an intentional
// change.
func TestSessionTokenExamples(t *testing.T) {
	update := os.Getenv("STRAZA_UPDATE_SPEC_EXAMPLES") == "1"
	if update {
		if err := os.MkdirAll(sessionTokenExampleDir(), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	known := map[string]bool{}
	var valid, invalid int
	for _, c := range sessionTokenExampleCases {
		known[c.file] = true
		path := filepath.Join(sessionTokenExampleDir(), c.file)
		want := buildSessionTokenExample(t, c)
		if update {
			if err := os.WriteFile(path, want, 0o644); err != nil {
				t.Fatal(err)
			}
		}
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("%s is missing. Regenerate the examples with STRAZA_UPDATE_SPEC_EXAMPLES=1: %v", c.file, err)
		}
		if !bytes.Equal(raw, want) {
			t.Errorf("%s differs from what the generator signs today. Regenerate it on purpose and explain the change in CHANGELOG.md.", c.file)
		}
		if strings.HasPrefix(c.file, "valid-") {
			valid++
		} else {
			invalid++
		}
		t.Run(c.file, func(t *testing.T) { replaySessionTokenExample(t, c.file, raw) })
	}
	files, err := filepath.Glob(filepath.Join(sessionTokenExampleDir(), "*.json"))
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range files {
		if !known[filepath.Base(f)] {
			t.Errorf("no case generates %s. Add a case for it or remove the file.", filepath.Base(f))
		}
	}
	if valid < 3 || invalid < 3 {
		t.Fatalf("%d valid and %d invalid examples, the spec asks for at least 3 of each", valid, invalid)
	}
}

// replaySessionTokenExample checks one example file as a third party would:
// its decoded header and claims match its token, and the verifier accepts
// or refuses it as its name says.
func replaySessionTokenExample(t *testing.T, name string, raw []byte) {
	var ex sessionTokenExample
	if err := json.Unmarshal(raw, &ex); err != nil {
		t.Fatalf("decode: %v", err)
	}
	if !strings.HasPrefix(ex.Provenance, "doc ") && !strings.HasPrefix(ex.Provenance, "live ") {
		t.Errorf("provenance %q does not say doc or live", ex.Provenance)
	}
	if !reflect.DeepEqual(headerOf(t, ex.SessionToken), ex.Header) || !reflect.DeepEqual(payloadOf(t, ex.SessionToken), ex.Claims) {
		t.Errorf("the token decodes to another header or claim set than the example shows")
	}
	keyJSON, err := json.Marshal(ex.Key)
	if err != nil {
		t.Fatal(err)
	}
	key, err := jwk.ParseKey(keyJSON)
	if err != nil {
		t.Fatalf("parse the published key: %v", err)
	}
	set := jwk.NewSet()
	if err := set.AddKey(key); err != nil {
		t.Fatal(err)
	}
	at, err := time.Parse(time.RFC3339, ex.At)
	if err != nil {
		t.Fatal(err)
	}
	svc := &TokenService{issuer: ex.Verifier.Issuer, verify: set}
	got, err := svc.verifyAt(ex.SessionToken, at)
	switch {
	case strings.HasPrefix(name, "valid-") && err != nil:
		t.Fatalf("a valid example is refused: %v", err)
	case strings.HasPrefix(name, "valid-"):
		want, _ := ex.Claims["eai"].(string)
		if got.EntraAgentID != want {
			t.Errorf("EntraAgentID = %q, want %q", got.EntraAgentID, want)
		}
	case ex.Reason == "":
		t.Fatal("an invalid example states no reason")
	case err == nil:
		t.Fatalf("an invalid example verifies: %+v", got)
	case !strings.Contains(err.Error(), "eai"):
		t.Errorf("refused for %v, but the example's reason is %q", err, ex.Reason)
	}
}
