// The grant examples come from fixed seeds and fixed times. Ed25519
// signatures are deterministic, so every byte of every example is
// reproducible, and TestGrantExamplesUpToDate pins the files to what
// signGrant, the signer MintGrant uses, produces today.
const (
	exampleGrantIssuer   = "https://straza.example"
	exampleGrantAudience = "https://ghapp.example"
	exampleGrantKID      = "5f1b3c2a-8d4e-4b6f-9a1c-2e7d0b3f4a51"
	exampleStrazaSeed    = 0x0a
	exampleOtherSeed     = 0x09
	exampleMachineSeed   = 0x07
)

var exampleGrantIat = time.Date(2026, 10, 24, 12, 0, 0, 0, time.UTC)

const exampleGrantProvenance = "doc spec/grant/SPEC.md 2026-10-24 (generated by TestGrantExamplesUpToDate, " +
	"not captured from strazad: the Straza session key from the Ed25519 seed of 32 bytes 0x0a with kid " +
	exampleGrantKID + ", the other key from 32 bytes 0x09, the machine key behind cnf.jkt from 32 bytes 0x07, " +
	"signed at 2026-10-24T12:00:00Z)"

// grantExampleCase is one example file and how to build it.
type grantExampleCase struct {
	file        string
	description string
	grant       func() Grant
	signer      byte   // the seed of the signing key, exampleStrazaSeed unless set
	typ         string // the header typ, GrantType unless set
	drop        string // a claim removed before signing
	reason      string // the rule an invalid example breaks
}

// exampleGrant is the fetch grant the examples start from.
func exampleGrant() Grant {
	return Grant{
		Audience: exampleGrantAudience,
		Subject:  "0199f3a2-5b7c-7d10-8e2f-3a4b5c6d7e01",
		Session:  "0199f3a2-6c8d-7e21-9f30-4b5c6d7e8f02",
		Harness:  "claude-code/2.1.0",
		Kind:     "human",
		JKT:      dpop.Thumbprint(testProofKey(exampleMachineSeed).Public().(ed25519.PublicKey)),
		Server:   "ghapp",
		ObjType:  "repo",
		ObjValue: "acme/billing",
		ObjID:    "684219301",
		Op:       "fetch",
		Decision: "019a1b2c-3d4e-7f50-8a61-7b8c9d0e1f01",
		JTI:      "0b7c6f0e-1d2a-4c3b-8e5f-6a7b8c9d0e01",
		IssuedAt: exampleGrantIat,
		Expiry:   exampleGrantIat.Add(GrantTTL),
	}
}

func examplePush(refs ...GrantRef) Grant {
	g := exampleGrant()
	g.Op, g.Refs = "push", refs
	g.Decision, g.JTI = "019a1b2c-3d4e-7f50-8a61-7b8c9d0e1f02", "0b7c6f0e-1d2a-4c3b-8e5f-6a7b8c9d0e02"
	return g
}

