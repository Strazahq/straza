// exampleKeyRecord is the signing key record of the given seed under the
// example kid.
func exampleKeyRecord(fill byte) store.SigningKey {
	priv := testProofKey(fill)
	return store.SigningKey{KID: exampleGrantKID, Purpose: store.KeyPurposeSession, Status: store.KeyActive,
		PrivateKey: priv.Seed(), PublicKey: priv.Public().(ed25519.PublicKey)}
}

// buildGrantExample signs one example and returns its file bytes.
func buildGrantExample(t *testing.T, c grantExampleCase) []byte {
	t.Helper()
	signer := c.signer
	if signer == 0 {
		signer = exampleStrazaSeed
	}
	priv, err := importPrivate(exampleKeyRecord(signer))
	if err != nil {
		t.Fatal(err)
	}
	g := c.grant()
	if !strings.HasPrefix(c.file, "invalid-") {
		if err := checkGrant(g); err != nil {
			t.Fatalf("%s: a valid example breaks an issuance rule: %v", c.file, err)
		}
	}
	payload, err := grantPayload(exampleGrantIssuer, g)
	if err != nil {
		t.Fatal(err)
	}
	if c.drop != "" {
		var m map[string]any
		if err := json.Unmarshal(payload, &m); err != nil {
			t.Fatal(err)
		}
		delete(m, c.drop)
		if payload, err = json.Marshal(m); err != nil {
			t.Fatal(err)
		}
	}
	typ := c.typ
	if typ == "" {
		typ = GrantType
	}
	signed, err := signGrantPayload(priv, typ, payload)
	if err != nil {
		t.Fatal(err)
	}

	pub, err := importPublic(exampleKeyRecord(exampleStrazaSeed))
	if err != nil {
		t.Fatal(err)
	}
	ex := grantExample{Provenance: exampleGrantProvenance, Description: c.description,
		At: exampleGrantIat.Add(30 * time.Second).Format(time.RFC3339), Grant: signed,
		Key: jsonMap(t, pub), Header: headerOf(t, signed), Claims: payloadOf(t, signed), Reason: c.reason}
	ex.Verifier.Issuer, ex.Verifier.Audience = exampleGrantIssuer, exampleGrantAudience

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(ex); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

// jsonMap round-trips a public key through JSON into a map.
func jsonMap(t *testing.T, key jwk.Key) map[string]any {
	t.Helper()
	b, err := json.Marshal(key)
	if err != nil {
		t.Fatal(err)
	}
	var m map[string]any
	if err := json.Unmarshal(b, &m); err != nil {
		t.Fatal(err)
	}
	return m
}

// TestGrantExamplesUpToDate regenerates every spec/grant example and
// compares bytes. After an intentional change to the grant format, run it
// with STRAZA_UPDATE_SPEC_EXAMPLES=1 to write the files, and commit them
// with the CHANGELOG line that explains the change. A file in the folder
// that no case generates is an error.
func TestGrantExamplesUpToDate(t *testing.T) {
	update := os.Getenv("STRAZA_UPDATE_SPEC_EXAMPLES") == "1"
	if update {
		if err := os.MkdirAll(grantExampleDir(), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	known := map[string]bool{}
	for _, c := range grantExampleCases {
		known[c.file] = true
		want := buildGrantExample(t, c)
		path := filepath.Join(grantExampleDir(), c.file)
		if update {
			if err := os.WriteFile(path, want, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(path)
		if err != nil {
			t.Errorf("%s is missing. Regenerate the examples with STRAZA_UPDATE_SPEC_EXAMPLES=1 go test ./internal/authn/ -run TestGrantExamplesUpToDate: %v", c.file, err)
			continue
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s differs from what the generator signs today. Regenerate it on purpose and explain the change in CHANGELOG.md.", c.file)
		}
	}
	files, err := filepath.Glob(filepath.Join(grantExampleDir(), "*.json"))
	if err != nil {
		t.Fatal(err)
	}
	var stray []string
	for _, f := range files {
		if !known[filepath.Base(f)] {
			stray = append(stray, filepath.Base(f))
		}
	}
	sort.Strings(stray)
	if len(stray) > 0 {
		t.Errorf("no case generates %v. Add a case for each file or remove the file.", stray)
	}
}
